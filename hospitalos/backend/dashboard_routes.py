"""
backend/dashboard_routes.py — Summary numbers for the Dashboard + simple report files.

  GET  /stats                 counts for the dashboard cards, charts and alerts
  GET  /reports               list report files in hospitalos/reports/
  GET  /reports/{name}        read one report file
  POST /reports/occupancy     write a new bed-occupancy report into reports/
"""

from collections import Counter
from datetime import datetime, timedelta, timezone

from fastapi import APIRouter, Depends, HTTPException
from sqlalchemy.orm import Session

from . import models
from .database import PROJECT_ROOT, get_db

router = APIRouter(tags=["Dashboard & Reports"])
REPORTS_DIR = PROJECT_ROOT / "reports"
LOW_STOCK_THRESHOLD = 50


@router.get("/stats")
def get_stats(db: Session = Depends(get_db)):
    """All numbers the Dashboard needs, in one request. Works on an empty database too."""
    wards = db.query(models.Ward).order_by(models.Ward.id).all()
    beds = db.query(models.Bed).all()
    ward_rows = []
    for w in wards:
        ward_beds = [b for b in beds if b.ward_id == w.id]
        occupied = sum(1 for b in ward_beds if b.is_occupied)
        ward_rows.append({"ward": w.name, "total": len(ward_beds), "occupied": occupied,
                          "free": len(ward_beds) - occupied})

    low_stock = (db.query(models.Medicine)
                 .filter(models.Medicine.stock_quantity < LOW_STOCK_THRESHOLD)
                 .order_by(models.Medicine.stock_quantity).all())
    unpaid = db.query(models.Bill).filter(models.Bill.paid_status != "Paid").all()

    # Appointments per day for the next 7 days (status Scheduled)
    today = datetime.now(timezone.utc).date()
    week = [today + timedelta(days=i) for i in range(7)]
    appts = db.query(models.Appointment).filter(models.Appointment.status == "Scheduled").all()
    per_day = Counter(a.appointment_time.date() for a in appts)

    pending_labs = db.query(models.LabTest).filter(models.LabTest.status == "Pending").count()
    occupied_total = sum(r["occupied"] for r in ward_rows)

    alerts = []
    for r in ward_rows:
        if r["total"] and r["occupied"] / r["total"] >= 0.85:
            alerts.append({"level": "critical", "title": f"{r['ward']} nearly full",
                           "detail": f"{r['occupied']} of {r['total']} beds occupied"})
    for m in low_stock[:5]:
        alerts.append({"level": "critical" if m.stock_quantity < 20 else "warning",
                       "title": f"Low stock: {m.name}", "detail": f"{m.stock_quantity} units left"})
    if pending_labs:
        alerts.append({"level": "info", "title": f"{pending_labs} lab tests pending",
                       "detail": "Awaiting results"})

    return {
        "patients_total": db.query(models.Patient).count(),
        "patients_admitted": db.query(models.Patient).filter(models.Patient.is_admitted == True).count(),  # noqa: E712
        "beds_total": len(beds),
        "beds_occupied": occupied_total,
        "beds_free": len(beds) - occupied_total,
        "doctors_available": db.query(models.Doctor).filter(models.Doctor.is_available == True).count(),  # noqa: E712
        "low_stock_count": len(low_stock),
        "unpaid_bills_count": len(unpaid),
        "unpaid_amount": round(sum(b.total_amount for b in unpaid), 2),
        "pending_labs": pending_labs,
        "wards": ward_rows,
        "appointments_next_7_days": [{"date": d.isoformat(), "count": per_day.get(d, 0)} for d in week],
        "alerts": alerts,
    }


def _safe_report_path(name: str):
    """Only allow plain file names inside reports/ (blocks '../' tricks)."""
    path = (REPORTS_DIR / name).resolve()
    if path.parent != REPORTS_DIR.resolve() or not path.is_file():
        raise HTTPException(status_code=404, detail=f"Report '{name}' not found")
    return path


@router.get("/reports")
def list_reports():
    """List report files (newest first)."""
    REPORTS_DIR.mkdir(exist_ok=True)
    files = sorted((p for p in REPORTS_DIR.iterdir() if p.is_file()), key=lambda p: p.stat().st_mtime, reverse=True)
    return [{"name": p.name, "size_bytes": p.stat().st_size,
             "modified": datetime.fromtimestamp(p.stat().st_mtime, timezone.utc).isoformat()} for p in files]


@router.get("/reports/{name}")
def read_report(name: str):
    """Return the text of one report file."""
    path = _safe_report_path(name)
    return {"name": path.name, "content": path.read_text(encoding="utf-8")}


@router.post("/reports/occupancy", status_code=201)
def create_occupancy_report(db: Session = Depends(get_db)):
    """Write a Markdown bed-occupancy + alerts report into reports/ and return its name."""
    stats = get_stats(db)
    now = datetime.now()
    lines = [
        f"# Bed Occupancy Report — {now:%Y-%m-%d %H:%M}",
        "",
        "_Synthetic data generated by HospitalOS._",
        "",
        f"- Beds occupied: **{stats['beds_occupied']} / {stats['beds_total']}**",
        f"- Patients admitted: **{stats['patients_admitted']}**",
        f"- Pending lab tests: **{stats['pending_labs']}**",
        f"- Unpaid bills: **{stats['unpaid_bills_count']}** (total {stats['unpaid_amount']:.2f})",
        "",
        "| Ward | Occupied | Free | Total |",
        "|------|---------:|-----:|------:|",
        *[f"| {w['ward']} | {w['occupied']} | {w['free']} | {w['total']} |" for w in stats["wards"]],
        "",
        "## Alerts",
        *([f"- **{a['title']}** — {a['detail']}" for a in stats["alerts"]] or ["- None"]),
        "",
    ]
    REPORTS_DIR.mkdir(exist_ok=True)
    name = f"occupancy_{now:%Y%m%d_%H%M%S}.md"
    (REPORTS_DIR / name).write_text("\n".join(lines), encoding="utf-8")
    return {"name": name}
